def operational_tool_counts() -> tuple[int, int]:
    """Return model-callable and deterministic-workflow catalogue counts."""

    model_count = sum(item.execution_mode is not Mode.DETERMINISTIC_WORKFLOW for item in OPERATIONAL_TOOL_CATALOG)
    return model_count, len(OPERATIONAL_TOOL_CATALOG) - model_count
