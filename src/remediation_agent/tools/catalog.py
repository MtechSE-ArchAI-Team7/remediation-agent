def _tool(
    tool_id: str,
    operation: str,
    boundary: str,
    category: Category,
    execution_mode: Mode,
    effect: Effect,
    availability: Availability,
    description: str,
    *controls: str,
    arguments: tuple[str, ...] = (),
) -> OperationalToolDescriptor:
    return OperationalToolDescriptor(
        tool_id=tool_id,
        operation=operation,
        boundary=boundary,
        category=category,
        execution_mode=execution_mode,
        effect=effect,
        availability=availability,
        description=description,
        arguments=arguments,
        controls=controls,
    )


